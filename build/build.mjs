import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';

const root = resolve(new URL('..', import.meta.url).pathname);
const dist = resolve(root, 'dist');
mkdirSync(dist, { recursive: true });

const files = [
  'src/core/config.js','src/core/state.js','src/core/events.js','src/lib/utils.js','src/lib/supabase.js','src/lib/cloudinary.js',
  'src/services/auth.service.js','src/services/profile.service.js','src/services/competition.service.js','src/services/registration.service.js','src/services/attempt.service.js','src/services/leaderboard.service.js','src/services/award.service.js','src/services/notification.service.js','src/services/order.service.js','src/services/admin.service.js','src/services/controlplane.service.js',
  'src/components/Toast.js','src/components/Modal.js','src/components/Skeleton.js','src/components/EmptyState.js','src/components/CompetitionCard.js','src/components/Header.js','src/components/Sidebar.js','src/components/BottomNav.js',
  'src/pages/Home.js','src/pages/Lomba.js','src/pages/Competition.js','src/pages/Registration.js','src/pages/Profile.js','src/pages/Leaderboard.js','src/pages/Awards.js','src/pages/Orders.js','src/pages/Verify.js','src/pages/Admin.js','src/pages/Organizer.js','src/pages/Placeholder.js','src/core/router.js','src/core/app.js'
];

function readList(list) {
  return list.map(file => `/* ${file} */\n${readFileSync(resolve(root, file), 'utf8')}`).join('\n\n');
}

function hashContent(content) {
  return createHash('sha256').update(content).digest('hex').slice(0, 12);
}

function gitSha() {
  if (process.env.GITHUB_SHA) return process.env.GITHUB_SHA;
  try { return execSync('git rev-parse HEAD', { cwd: root, encoding: 'utf8' }).trim(); }
  catch { return 'local-dev'; }
}

function removeOldFingerprints() {
  for (const name of readdirSync(dist)) {
    if (/^(app|styles|vendor)\.[a-f0-9]{12}\./.test(name)) unlinkSync(resolve(dist, name));
  }
}

removeOldFingerprints();

const source = readList(files);
const app = source;
const appMin = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s*\n/g, '\n');
const styles = readFileSync(resolve(root, 'src/styles/styles.css'), 'utf8').replace(/\/\*[^]*?\*\//g, '').replace(/\n+/g, '\n');
const vendor = '/* Vendor libraries are loaded from official CDNs in the Blogger theme: Supabase JS and Cloudinary Upload Widget. */';

const appHash = hashContent(appMin);
const stylesHash = hashContent(styles);
const vendorHash = hashContent(vendor);

const appFile = `app.${appHash}.min.js`;
const stylesFile = `styles.${stylesHash}.min.css`;
const vendorFile = `vendor.${vendorHash}.min.js`;

writeFileSync(resolve(dist, appFile), appMin);
writeFileSync(resolve(dist, stylesFile), styles);
writeFileSync(resolve(dist, vendorFile), vendor);

// Keep deterministic local inspection artifacts too.
writeFileSync(resolve(dist, 'app.js'), app);
writeFileSync(resolve(dist, 'app.min.js'), appMin);
writeFileSync(resolve(dist, 'styles.min.css'), styles);
writeFileSync(resolve(dist, 'vendor.min.js'), vendor);

const release = gitSha();
const base = 'https://cdn.jsdelivr.net/gh/taufx98/sykabelajar-frontend@main/dist';
const loader = `/* Sykabelajar release loader - generated by build/build.mjs */\n(function(){\n  if (window.__SYKA_LOADER_STARTED__) return;\n  window.__SYKA_LOADER_STARTED__ = true;\n  const release = ${JSON.stringify(release)};\n  const base = ${JSON.stringify(base)};\n  const files = {\n    styles: ${JSON.stringify(stylesFile)},\n    vendor: ${JSON.stringify(vendorFile)},\n    app: ${JSON.stringify(appFile)}\n  };\n  window.__SYKA_RELEASE__ = { commit: release, files: { ...files } };\n  window.SYKA_CONFIG = window.SYKA_CONFIG || {};\n  window.SYKA_CONFIG.ASSET_RELEASE = release;\n  window.SYKA_CONFIG.ASSET_BASE_URL = base;\n  const css = document.createElement('link');\n  css.rel = 'stylesheet';\n  css.href = base + '/' + files.styles;\n  css.dataset.sykaRelease = release;\n  document.head.appendChild(css);\n  function load(src, attrs, done){\n    const s = document.createElement('script');\n    s.src = src;\n    for (const [key,value] of Object.entries(attrs || {})) s.setAttribute(key, value);\n    s.dataset.sykaRelease = release;\n    if (done) s.onload = done;\n    s.onerror = function(){ console.error('[Sykabelajar] failed to load', src); };\n    document.head.appendChild(s);\n  }\n  load(base + '/' + files.vendor, {}, function(){
    load(base + '/' + files.app, { 'data-syka-app': '1' }, function(){
      try {
        if (window.SYKA_APP && typeof window.SYKA_APP.init === 'function') {
          window.SYKA_APP.init();
        } else {
          console.error('[Sykabelajar] SYKA_APP.init() tidak ditemukan setelah app bundle dimuat.');
        }
      } catch (e) {
        console.error('[Sykabelajar] App initialization failed:', e);
      }
    });
  });
})();\n`;
writeFileSync(resolve(dist, 'loader.js'), loader);

const manifest = {
  app: appFile,
  styles: stylesFile,
  vendor: vendorFile,
  loader: 'loader.js',
  commit: release,
  generatedAt: new Date().toISOString()
};
writeFileSync(resolve(dist, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

